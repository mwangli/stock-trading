CREATE TABLE IF NOT EXISTS trade_decision_context (
    context_id VARCHAR(64) NOT NULL,
    context_hash VARCHAR(64) NOT NULL,
    candidate_batch_id VARCHAR(128) NOT NULL,
    stock_code VARCHAR(32) NOT NULL,
    context_json LONGTEXT NOT NULL,
    information_cutoff_at DATETIME(6) NOT NULL,
    expires_at DATETIME(6) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (context_id),
    UNIQUE KEY uk_trade_decision_context_hash (context_hash),
    KEY idx_trade_decision_context_batch (candidate_batch_id, created_at),
    KEY idx_trade_decision_context_expire (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS agent_trade_decision (
    decision_id VARCHAR(64) NOT NULL,
    context_id VARCHAR(64) NOT NULL,
    context_hash VARCHAR(64) NOT NULL,
    candidate_batch_id VARCHAR(128) NOT NULL,
    stock_code VARCHAR(32) NOT NULL,
    recommendation VARCHAR(16) NOT NULL,
    reason_codes TEXT NOT NULL,
    summary VARCHAR(500) NOT NULL,
    thesis TEXT NULL,
    supporting_evidence_refs TEXT NOT NULL,
    contrary_evidence_refs TEXT NOT NULL,
    risk_flags TEXT NOT NULL,
    invalidation_conditions TEXT NOT NULL,
    suggested_priority INT NULL,
    allocation_min DOUBLE NULL,
    allocation_max DOUBLE NULL,
    confidence_band VARCHAR(16) NOT NULL,
    decision_mode VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    fusion_outcome VARCHAR(32) NOT NULL,
    impacted BIT(1) NOT NULL,
    fusion_reason VARCHAR(500) NOT NULL,
    provider VARCHAR(32) NULL,
    model VARCHAR(128) NULL,
    prompt_version VARCHAR(32) NOT NULL,
    uncertainty TEXT NULL,
    valid_until DATETIME(6) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    PRIMARY KEY (decision_id),
    UNIQUE KEY uk_agent_trade_decision_context_version (context_hash, prompt_version, decision_mode),
    KEY idx_agent_trade_decision_batch (candidate_batch_id, created_at),
    KEY idx_agent_trade_decision_status (status, valid_until),
    CONSTRAINT fk_agent_trade_decision_context
        FOREIGN KEY (context_id) REFERENCES trade_decision_context (context_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
